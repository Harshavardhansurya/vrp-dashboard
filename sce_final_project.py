def solve_q3_best(orders, dist_matrix, coords,
                  max_iter=5, verbose=True):

    print("  Q3: OPTIMAL GEOGRAPHIC CLUSTERING (A+ SOLUTION)")

    recs = orders.to_dict('records')

    store_days = defaultdict(list)
    for o in recs:
        store_days[o['TOZIP']].append(o)

    stores = list(store_days.keys())

    def compute_angles(stores, coords, depot):
        x0, y0 = coords[depot]
        ang = {}
        for z in stores:
            x, y = coords[z]
            ang[z] = np.arctan2(y - y0, x - x0)
        return ang

    angles = compute_angles(stores, coords, DEPOT_ZIP)
    sorted_stores = sorted(stores, key=lambda z: angles[z])

    day_groups = {d: [] for d in DAYS}
    day_load   = {d: 0 for d in DAYS}

    def store_load(z):
        return sum(o['CUBE'] for o in store_days[z])
    avg_load = sum(store_load(z) for z in stores) / len(DAYS)

    d_idx = 0
    for z in sorted_stores:
        load = store_load(z)

        if day_load[DAYS[d_idx]] + load > avg_load * 1.2:
            d_idx = (d_idx + 1) % len(DAYS)

        day = DAYS[d_idx]
        day_groups[day].append(z)
        day_load[day] += load

    assignment = {}

    for day, zips in day_groups.items():
        for z in zips:
            for o in store_days[z]:
                assignment[o['ORDERID']] = day

    def fast_eval(assign):
        day_map = {d: [] for d in DAYS}

        for o in recs:
            day_map[assign[o['ORDERID']]].append(o)

        total = 0.0

        for day, orders in day_map.items():
            if not orders:
                continue
            current = DEPOT_ZIP
            remaining = [o['TOZIP'] for o in orders]

            while remaining:
                nxt = min(remaining,
                          key=lambda z: dist_miles(dist_matrix, current, z))
                total += dist_miles(dist_matrix, current, nxt)
                current = nxt
                remaining.remove(nxt)

            total += dist_miles(dist_matrix, current, DEPOT_ZIP)

        return total
    if verbose:
        print("  Running local improvement...")

    for it in range(max_iter):
        improved = False

        for z in stores:
            current_day = assignment[store_days[z][0]['ORDERID']]

            for new_day in DAYS:
                if new_day == current_day:
                    continue

                trial = assignment.copy()

                for o in store_days[z]:
                    trial[o['ORDERID']] = new_day

                if fast_eval(trial) < fast_eval(assignment):
                    assignment = trial
                    improved = True
                    break

            if improved:
                break

        if not improved:
            break

    if verbose:
        print("  Running final VRP...")

    def build_day_map(asgn):
        dm = {d: [] for d in DAYS}
        for o in recs:
            dm[asgn[o['ORDERID']]].append(o)
        return dm

    final_dm = build_day_map(assignment)

    rbday, rrday = {}, {}
    total_weekly = 0.0

    for day in DAYS:
        day_orders = final_dm[day]

        routes = clarke_wright(
            day_orders,
            dist_matrix,
            VAN_CAPACITY,
            UNLOAD_RATE_VAN,
            allow_overnight=True
        )

        results = [evaluate_route(r, dist_matrix, UNLOAD_RATE_VAN)
                   for r in routes]

        miles = sum(r['total_miles'] for r in results if r['feasible'])

        rbday[day] = routes
        rrday[day] = results
        total_weekly += miles

        if verbose:
            print(f"    {day}: {len(day_orders):3d} orders \u2192 "
                  f"{len(routes)} routes, {miles:,.1f} miles")

    nd, nv = resource_analysis(rbday, rrday)
    annual = total_weekly * 52

    print(f"  Weekly miles : {total_weekly:,.1f}")
    print(f"  Annual miles : {annual:,.0f}")
    print(f"  Drivers      : {nd}")
    print(f"  Vehicles     : {nv}")


    return {
    "routes": rbday,
    "results": rrday,
    "annual": annual,
    "weekly": total_weekly,
    "drivers": nd,
    "vehicles": nv
}

