def _hhmm(h):
    if h is None or (isinstance(h, float) and np.isnan(h)):
        return ''
    hh = int(h) % 24; mm = int(round((h % 1) * 60))
    if mm == 60: hh += 1; mm = 0
    return f"{hh:02d}:{mm:02d}"


