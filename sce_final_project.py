#Constants
SPEED_MPH       = 40.0
UNLOAD_RATE_VAN = 0.030
UNLOAD_RATE_ST  = 0.043
MIN_UNLOAD_MIN  = 30.0
MAX_DRIVE_HRS   = 11.0
MAX_DUTY_HRS    = 14.0
BREAK_HRS       = 10.0
STORE_OPEN_H    = 8.0
STORE_CLOSE_H   = 18.0

VAN_CAPACITY    = 3200
ST_CAPACITY     = 1400
DEPOT_ZIP       = 1887

DAY_BASE_HRS = {'Mon': 0.0, 'Tue': 24.0, 'Wed': 48.0, 'Thu': 72.0, 'Fri': 96.0}
DAYS = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri']

"""Data Loading"""

def load_data(deliveries_path='deliveries.xlsx', distances_path='distances.xlsx'):
    import warnings
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        df_order = pd.read_excel(deliveries_path, sheet_name='OrderTable')
        df_loc   = pd.read_excel(deliveries_path, sheet_name='LocationTable')
        df_dist  = pd.read_excel(distances_path,  sheet_name='Sheet1', index_col=0)

    df_dist = df_dist.drop(index='Zip').drop(columns='Unnamed: 1')
    df_dist.index   = df_dist.index.astype(int)
    df_dist.columns = df_dist.columns.astype(int)
    dist = df_dist.astype(float)

    orders = df_order[df_order['ORDERID'] != 0].copy()
    orders['CUBE'] = pd.to_numeric(orders['CUBE'], errors='coerce')
    orders = orders.reset_index(drop=True)
    return orders, df_loc, dist


def dist_miles(dist_matrix, z1, z2):
    try:
        return float(dist_matrix.loc[z1, z2])
    except KeyError:
        return float('inf')

"""Time & Feasability Helpers"""

def travel_hrs(miles):
    return miles / SPEED_MPH

def unload_hrs(cube, rate):
    return max(rate * cube, MIN_UNLOAD_MIN) / 60.0

def vol_ok(route, capacity):
    return sum(o['CUBE'] for o in route) <= capacity


def evaluate_route(route, dist_matrix, unload_rate, allow_overnight=True):
    """
    Simulate a route and check all constraints.
    Returns dict: feasible, total_miles, drive_hrs, duty_hrs,
                  departure_time, arrival_back_time, is_overnight, stops, reason.
    """
    if not route:
        return {'feasible': False, 'reason': 'empty route',
                'total_miles': 0, 'drive_hrs': 0, 'duty_hrs': 0,
                'departure_time': 0, 'arrival_back_time': 0,
                'is_overnight': False, 'stops': []}

    first_zip   = route[0]['TOZIP']
    d_to_first  = dist_miles(dist_matrix, DEPOT_ZIP, first_zip)
    depart_time = STORE_OPEN_H - travel_hrs(d_to_first)

    drive = 0.0; duty = 0.0
    cur   = depart_time
    prev  = DEPOT_ZIP
    total_miles = 0.0
    overnight   = False
    stops = []

    for idx, order in enumerate(route):
        dest  = order['TOZIP']
        miles = dist_miles(dist_matrix, prev, dest)
        t_drv = travel_hrs(miles)
        t_unl = unload_hrs(order['CUBE'], unload_rate)

        drive_after = drive + t_drv
        duty_after  = duty  + t_drv

        if drive_after > MAX_DRIVE_HRS + 1e-9 or duty_after > MAX_DUTY_HRS + 1e-9:
            if not allow_overnight or overnight:
                return {'feasible': False, 'total_miles': total_miles,
                        'drive_hrs': drive, 'duty_hrs': duty,
                        'departure_time': depart_time,
                        'arrival_back_time': cur,
                        'is_overnight': overnight, 'stops': stops,
                        'reason': f'DOT violation before stop {idx+1} '
                                  f'(order {order["ORDERID"]})'}

            rem_drive = MAX_DRIVE_HRS - drive
            rem_duty  = MAX_DUTY_HRS  - duty
            can_drive = min(rem_drive, rem_duty)

            if can_drive >= t_drv:
                drive += t_drv; duty += t_drv; cur += t_drv
            else:
                cur += can_drive
                cur += BREAK_HRS
                overnight = True
                drive = 0.0; duty = 0.0

                rem_t = t_drv - can_drive
                if rem_t < 0: rem_t = 0
                drive += rem_t; duty += rem_t; cur += rem_t
        else:
            drive += t_drv; duty += t_drv; cur += t_drv

        total_miles += miles

        if cur < STORE_OPEN_H:
            wait  = STORE_OPEN_H - cur
            duty += wait
            cur   = STORE_OPEN_H

        arrival = cur

        if arrival > STORE_CLOSE_H + 1e-9:
            return {'feasible': False, 'total_miles': total_miles,
                    'drive_hrs': drive, 'duty_hrs': duty,
                    'departure_time': depart_time,
                    'arrival_back_time': cur,
                    'is_overnight': overnight, 'stops': stops,
                    'reason': f'Arrives after 18:00 at stop {idx+1} '
                              f'(order {order["ORDERID"]}, zip {dest})'}

        duty += t_unl; cur += t_unl

        if duty > MAX_DUTY_HRS + 1e-9 and not overnight:
            return {'feasible': False, 'total_miles': total_miles,
                    'drive_hrs': drive, 'duty_hrs': duty,
                    'departure_time': depart_time,
                    'arrival_back_time': cur,
                    'is_overnight': overnight, 'stops': stops,
                    'reason': f'Duty exceeded after unload stop {idx+1}'}

        stops.append({'order_id': order['ORDERID'], 'zip': dest,
                      'arrival': arrival, 'departure': cur,
                      'drive_cumul': drive, 'duty_cumul': duty})
        prev = dest

    d_ret = dist_miles(dist_matrix, prev, DEPOT_ZIP)
    total_miles += d_ret
    drive += travel_hrs(d_ret)
    duty  += travel_hrs(d_ret)
    cur   += travel_hrs(d_ret)

    return {'feasible': True, 'total_miles': total_miles,
            'drive_hrs': drive, 'duty_hrs': duty,
            'departure_time': depart_time, 'arrival_back_time': cur,
            'is_overnight': overnight, 'stops': stops, 'reason': None}

"""CONSTRUCTION – CLARKE-WRIGHT SAVINGS"""

def clarke_wright(day_orders, dist_matrix, capacity, unload_rate,
                  allow_overnight=True):
    orders = list(day_orders)
    n = len(orders)
    if n == 0:
        return []

    savings = []
    for i in range(n):
        for j in range(i + 1, n):
            zi = orders[i]['TOZIP']; zj = orders[j]['TOZIP']
            s = (dist_miles(dist_matrix, DEPOT_ZIP, zi)
                 + dist_miles(dist_matrix, DEPOT_ZIP, zj)
                 - dist_miles(dist_matrix, zi, zj))
            savings.append((s, i, j))
    savings.sort(reverse=True)

    routes = [[o] for o in orders]
    which  = list(range(n))

    def try_merge(ri, rj, new_seq):
        if not vol_ok(new_seq, capacity): return False
        if not evaluate_route(new_seq, dist_matrix, unload_rate,
                              allow_overnight)['feasible']: return False
        routes[ri] = new_seq
        for k in range(n):
            if which[k] == rj: which[k] = ri
        routes[rj] = []
        return True

    for s, i, j in savings:
        ri = which[i]; rj = which[j]
        if ri == rj or not routes[ri] or not routes[rj]:
            continue
        r_i = routes[ri]; r_j = routes[rj]
        oi  = orders[i]['ORDERID']; oj = orders[j]['ORDERID']
        if   r_i[-1]['ORDERID'] == oi and r_j[0]['ORDERID'] == oj:
            try_merge(ri, rj, r_i + r_j)
        elif r_i[0]['ORDERID'] == oi and r_j[-1]['ORDERID'] == oj:
            try_merge(rj, ri, r_j + r_i)
        elif r_i[-1]['ORDERID'] == oj and r_j[0]['ORDERID'] == oi:
            try_merge(ri, rj, r_i + r_j)
        elif r_i[0]['ORDERID'] == oj and r_j[-1]['ORDERID'] == oi:
            try_merge(rj, ri, r_j + r_i)

    return [r for r in routes if r]

"""IMPROVEMENT – LOCAL SEARCH"""

def two_opt(route, dist_matrix, unload_rate, cap, allow_overnight=True):
    best = list(route)
    best_r = evaluate_route(best, dist_matrix, unload_rate, allow_overnight)
    if not best_r['feasible']:
        return best, best_r
    improved = True
    while improved:
        improved = False
        n = len(best)
        for i in range(n - 1):
            for j in range(i + 2, n):
                cand = best[:i] + best[i:j][::-1] + best[j:]
                if not vol_ok(cand, cap): continue
                r = evaluate_route(cand, dist_matrix, unload_rate, allow_overnight)
                if r['feasible'] and r['total_miles'] < best_r['total_miles'] - 0.01:
                    best = cand; best_r = r; improved = True
    return best, best_r


def or_opt(route, dist_matrix, unload_rate, cap, seg=1, allow_overnight=True):
    best = list(route)
    best_r = evaluate_route(best, dist_matrix, unload_rate, allow_overnight)
    if not best_r['feasible']:
        return best, best_r
    improved = True
    while improved:
        improved = False
        n = len(best)
        for i in range(n - seg + 1):
            chunk = best[i:i + seg]
            rest  = best[:i] + best[i + seg:]
            for j in range(len(rest) + 1):
                cand = rest[:j] + chunk + rest[j:]
                if cand == best: continue
                if not vol_ok(cand, cap): continue
                r = evaluate_route(cand, dist_matrix, unload_rate, allow_overnight)
                if r['feasible'] and r['total_miles'] < best_r['total_miles'] - 0.01:
                    best = cand; best_r = r; improved = True
                    break
            if improved: break
    return best, best_r


def inter_route_relocate(routes, dist_matrix, unload_rate, cap,
                         allow_overnight=True):
    res = [evaluate_route(r, dist_matrix, unload_rate, allow_overnight)
           for r in routes]
    improved = True
    while improved:
        improved = False
        for i in range(len(routes)):
            for si in range(len(routes[i])):
                order   = routes[i][si]
                new_ri  = routes[i][:si] + routes[i][si+1:]
                mi_old  = res[i]['total_miles']

                if new_ri:
                    r_new_i = evaluate_route(new_ri, dist_matrix, unload_rate,
                                              allow_overnight)
                    if not r_new_i['feasible']: continue
                    mi_new_i = r_new_i['total_miles']
                else:
                    r_new_i  = None
                    mi_new_i = 0.0

                for j in range(len(routes)):
                    if i == j: continue
                    for sj in range(len(routes[j]) + 1):
                        new_rj = routes[j][:sj] + [order] + routes[j][sj:]
                        if not vol_ok(new_rj, cap): continue
                        r_new_j = evaluate_route(new_rj, dist_matrix, unload_rate,
                                                  allow_overnight)
                        if not r_new_j['feasible']: continue
                        gain = (mi_old + res[j]['total_miles']) \
                             - (mi_new_i + r_new_j['total_miles'])
                        if gain > 0.1:
                            routes[i] = new_ri
                            routes[j] = new_rj
                            res[i]    = r_new_i if r_new_i else \
                                {'feasible': True, 'total_miles': 0,
                                 'drive_hrs': 0, 'duty_hrs': 0,
                                 'departure_time': 0, 'arrival_back_time': 0,
                                 'is_overnight': False, 'stops': [], 'reason': None}
                            res[j]    = r_new_j
                            improved  = True
                            break
                    if improved: break
                if improved: break
            if improved: break

    pairs = [(r, s) for r, s in zip(routes, res) if r]
    if pairs:
        routes, res = zip(*pairs)
        return list(routes), list(res)
    return [], []

"""Solving ONE DAY"""

def solve_day(day_orders, dist_matrix, capacity, unload_rate,
              allow_overnight=True, verbose=False):
    if not day_orders:
        return [], [], 0.0

    routes = clarke_wright(day_orders, dist_matrix, capacity,
                           unload_rate, allow_overnight)

    improved = []
    for r in routes:
        r, _ = two_opt(r, dist_matrix, unload_rate, capacity, allow_overnight)
        r, _ = or_opt(r, dist_matrix, unload_rate, capacity, seg=1,
                      allow_overnight=allow_overnight)
        r, _ = or_opt(r, dist_matrix, unload_rate, capacity, seg=2,
                      allow_overnight=allow_overnight)
        improved.append(r)
    routes = improved

    routes, results = inter_route_relocate(routes, dist_matrix, unload_rate,
                                           capacity, allow_overnight)

    final_results = [evaluate_route(r, dist_matrix, unload_rate, allow_overnight)
                     for r in routes]
    total_miles   = sum(r['total_miles'] for r in final_results if r['feasible'])

    if verbose:
        n_inf = sum(1 for r in final_results if not r['feasible'])
        n_on  = sum(1 for r in final_results if r.get('is_overnight'))
        print(f"    {len(routes)} routes | {total_miles:,.1f} mi | {n_on} overnight"
              + (f" | {n_inf} INFEASIBLE" if n_inf else ""))

    return routes, final_results, total_miles

"""Resource Analysis"""

def resource_analysis(routes_by_day, results_by_day):
    timeline = []
    for day in DAYS:
        base = DAY_BASE_HRS[day]
        for res in results_by_day.get(day, []):
            if not res.get('feasible'): continue
            timeline.append({'dispatch': base + res['departure_time'],
                             'finish':   base + res['arrival_back_time']})
    timeline.sort(key=lambda x: x['dispatch'])

    avail = []
    for t in timeline:
        assigned = False
        for k in range(len(avail)):
            if avail[k] + BREAK_HRS <= t['dispatch'] + 1e-9:
                avail[k] = t['finish']; assigned = True; break
        if not assigned:
            avail.append(t['finish'])

    events = []
    for t in timeline:
        events += [(t['dispatch'], +1), (t['finish'], -1)]
    events.sort()
    peak = cur = 0
    for _, d in events:
        cur += d; peak = max(peak, cur)

    return len(avail), peak

